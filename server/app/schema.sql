-- Sri Nikil ERP - PostgreSQL (Supabase) schema
-- Applied automatically by the backend on startup (idempotent).

CREATE TABLE IF NOT EXISTS counters (
  name TEXT PRIMARY KEY,
  seq BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS products (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code TEXT,
  name TEXT,
  cat TEXT,
  unit TEXT,
  price DOUBLE PRECISION,
  stock DOUBLE PRECISION,
  opening_stock DOUBLE PRECISION,
  sold DOUBLE PRECISION,
  image TEXT,
  created_at TIMESTAMPTZ,
  extra JSONB NOT NULL DEFAULT '{}'::jsonb
);

CREATE UNIQUE INDEX IF NOT EXISTS products_code_key
  ON products (code) WHERE code IS NOT NULL AND code <> '';

CREATE TABLE IF NOT EXISTS bills (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  bill_no TEXT,
  customer TEXT,
  phone TEXT,
  payment TEXT,
  items JSONB NOT NULL DEFAULT '[]'::jsonb,
  subtotal DOUBLE PRECISION,
  cgst DOUBLE PRECISION,
  sgst DOUBLE PRECISION,
  grand DOUBLE PRECISION,
  "by" TEXT,
  by_user TEXT,
  date TIMESTAMPTZ,
  expires_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ,
  extra JSONB NOT NULL DEFAULT '{}'::jsonb
);

CREATE INDEX IF NOT EXISTS bills_date_idx ON bills (date DESC);
CREATE INDEX IF NOT EXISTS bills_by_user_idx ON bills (LOWER(by_user));
CREATE INDEX IF NOT EXISTS bills_expires_at_idx ON bills (expires_at);

-- Audit trail for automatic retention purges (bills expired after 4 years).
CREATE TABLE IF NOT EXISTS deletion_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entity TEXT NOT NULL DEFAULT 'bill',
  entity_id BIGINT,
  bill_no TEXT,
  created_at TIMESTAMPTZ,
  expires_at TIMESTAMPTZ,
  deleted_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  reason TEXT,
  details JSONB NOT NULL DEFAULT '{}'::jsonb
);

CREATE INDEX IF NOT EXISTS deletion_log_deleted_at_idx ON deletion_log (deleted_at DESC);
CREATE INDEX IF NOT EXISTS deletion_log_entity_idx ON deletion_log (entity, entity_id);

CREATE TABLE IF NOT EXISTS sales (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  date TIMESTAMPTZ,
  extra JSONB NOT NULL DEFAULT '{}'::jsonb
);

CREATE TABLE IF NOT EXISTS customers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT,
  phone TEXT,
  first_visit TIMESTAMPTZ,
  last_visit TIMESTAMPTZ,
  visits DOUBLE PRECISION,
  total DOUBLE PRECISION,
  extra JSONB NOT NULL DEFAULT '{}'::jsonb
);

CREATE UNIQUE INDEX IF NOT EXISTS customers_phone_key
  ON customers (phone) WHERE phone IS NOT NULL AND phone <> '';

CREATE TABLE IF NOT EXISTS refills (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  date TIMESTAMPTZ,
  product_id BIGINT,
  product TEXT,
  qty DOUBLE PRECISION,
  "by" TEXT,
  created_at TIMESTAMPTZ,
  extra JSONB NOT NULL DEFAULT '{}'::jsonb
);

CREATE INDEX IF NOT EXISTS refills_date_idx ON refills (date DESC);

CREATE TABLE IF NOT EXISTS price_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  date TIMESTAMPTZ,
  product_id BIGINT,
  product TEXT,
  old_price DOUBLE PRECISION,
  new_price DOUBLE PRECISION,
  "by" TEXT,
  created_at TIMESTAMPTZ,
  extra JSONB NOT NULL DEFAULT '{}'::jsonb
);

CREATE INDEX IF NOT EXISTS price_history_date_idx ON price_history (date DESC);

CREATE TABLE IF NOT EXISTS accounts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username TEXT NOT NULL,
  pass TEXT,
  role TEXT,
  created_at TIMESTAMPTZ
);

CREATE UNIQUE INDEX IF NOT EXISTS accounts_username_key ON accounts (username);

ALTER TABLE accounts ADD COLUMN IF NOT EXISTS name TEXT;
ALTER TABLE accounts ADD COLUMN IF NOT EXISTS email TEXT;

-- Mirror of the Supabase Auth admin user (auth.users), shown in the
-- Supabase Dashboard Table Editor next to Authentication -> Users.
CREATE TABLE IF NOT EXISTS profiles (
  id UUID PRIMARY KEY,
  username TEXT UNIQUE,
  name TEXT,
  email TEXT,
  role TEXT,
  created_at TIMESTAMPTZ,
  updated_at TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS login_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username TEXT,
  user_name TEXT,
  role TEXT,
  login_time TEXT,
  logout_time TEXT,
  shift_session_id BIGINT,
  status TEXT,
  created_at TIMESTAMPTZ,
  extra JSONB NOT NULL DEFAULT '{}'::jsonb
);

CREATE INDEX IF NOT EXISTS login_logs_shift_session_idx ON login_logs (shift_session_id);
CREATE INDEX IF NOT EXISTS login_logs_login_time_idx ON login_logs (login_time DESC, logout_time DESC);

CREATE TABLE IF NOT EXISTS shifts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username TEXT,
  role TEXT,
  shift_start TEXT,
  shift_end TEXT,
  active BOOLEAN,
  recipient_email TEXT,
  login_log_cleared BOOLEAN,
  created_at TIMESTAMPTZ,
  extra JSONB NOT NULL DEFAULT '{}'::jsonb
);

CREATE INDEX IF NOT EXISTS shifts_user_active_idx ON shifts (username, active);

CREATE TABLE IF NOT EXISTS shift_reports (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id BIGINT,
  username TEXT,
  role TEXT,
  shift_start TIMESTAMPTZ,
  shift_end TIMESTAMPTZ,
  total_bills INTEGER,
  total_items_sold DOUBLE PRECISION,
  total_sales_amount DOUBLE PRECISION,
  payment_breakdown JSONB,
  products_sold JSONB,
  remaining_stock_summary JSONB,
  report_email TEXT,
  report_subject TEXT,
  email_status TEXT,
  email_error TEXT,
  email_sent_at TIMESTAMPTZ,
  attachment_name TEXT,
  attachment_count INTEGER,
  status TEXT,
  created_at TIMESTAMPTZ,
  extra JSONB NOT NULL DEFAULT '{}'::jsonb
);

ALTER TABLE shift_reports ADD COLUMN IF NOT EXISTS extra JSONB NOT NULL DEFAULT '{}'::jsonb;

CREATE INDEX IF NOT EXISTS shift_reports_role_end_idx ON shift_reports (LOWER(role), shift_end DESC);

CREATE TABLE IF NOT EXISTS settings (
  key TEXT PRIMARY KEY,
  gst DOUBLE PRECISION,
  shop TEXT,
  addr TEXT,
  gstin TEXT,
  fssai TEXT,
  phone TEXT
);
